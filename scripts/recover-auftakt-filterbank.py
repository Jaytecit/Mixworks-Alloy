"""Generate the native sparse filter table from the retained, hash-bound REA byte observation."""
import argparse
import hashlib
import json
from pathlib import Path

ARTIFACT = '0624710ff4805170c98558d3410966aafffeb1392489e728d488792ec3724340'
EVIDENCE = 'ev_52b5a7011b6889c69bd8753b199438985b2cfb9a38df7b65bedbefaf8f9ded7e'
FILTER_SHA256 = 'd60405abd2e5ae1de3635c7761bf602edeed80890ab92b4582d485974e116ae9'


def filters(evidence):
    records = json.loads(Path(evidence).read_text(encoding='utf-8'))['records']
    row = next(r for r in records if r['evidence_id'] == EVIDENCE)
    data = row['normalized_result']
    if (row['subject']['digest']['sha256'] != ARTIFACT or data['address'] != '0x1405015e0'
            or not data['complete'] or data['returned_bytes'] != 174888):
        raise ValueError('Wrong or incomplete filter-bank evidence.')
    raw = bytes.fromhex(data['bytes_hex'])
    if len(raw) != 174888 or raw[-1:] != b'\0' or hashlib.sha256(raw[:-1]).hexdigest() != FILTER_SHA256:
        raise ValueError('Invalid filter-bank carrier.')
    banks = json.loads(raw[:-1])
    for group, (size, count) in enumerate(zip((1024, 2048, 4096), (22, 46, 92))):
        bank = banks[str(group)]
        if set(bank) != {str(i) for i in range(count)}:
            raise ValueError('Unexpected band identities.')
        for band in bank.values():
            bins = sorted(map(int, band))
            if bins != list(range(bins[0], bins[-1] + 1)) or bins[0] < 0 or bins[-1] > size // 2:
                raise ValueError('Invalid band coverage.')
            if any(type(v) not in (int, float) or not 0 <= v <= 1 for v in band.values()):
                raise ValueError('Invalid coefficient.')
    return banks, hashlib.sha256(raw[:-1]).hexdigest()


def generate(evidence):
    banks, digest = filters(evidence)
    weights, bands = [], []
    for group in range(3):
        bank = banks[str(group)]
        for index in range(len(bank)):
            band = bank[str(index)]
            bins = sorted(map(int, band))
            bands.append((bins[0], len(weights), len(bins)))
            weights.extend(band[str(k)] for k in bins)
    def number(v):
        value = format(v, '.9g')
        return value + ('' if '.' in value or 'e' in value else '.0') + 'f'
    lines = ['// Generated by scripts/recover-auftakt-filterbank.py. Do not edit.',
             '// AUFTAKT 4.2.2; sparse frontend configuration, not a beat/bar network.',
             '// REA ' + EVIDENCE, '// JSON SHA-256 ' + digest,
             'struct RecoveredBand { int firstBin, offset, count; };',
             'static constexpr RecoveredBand recoveredBands[] = {']
    lines += ['    {' + ', '.join(map(str, band)) + '},' for band in bands]
    lines += ['};', 'static constexpr float recoveredWeights[] = {']
    lines += ['    ' + ', '.join(number(v) for v in weights[i:i + 8]) + ',' for i in range(0, len(weights), 8)]
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--evidence', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--model-output', type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.evidence), encoding='utf-8')
    if args.model_output:
        records = json.loads(args.evidence.read_text(encoding='utf-8'))['records']
        model = next(r for r in records if r['evidence_id'] == 'ev_47d7e821a18e919c1ce513282c5651c9b5e146afae4040366248e3c2dae8413d')
        data = model['normalized_result']
        raw = bytes.fromhex(data['bytes_hex'])
        if (model['subject']['digest']['sha256'] != ARTIFACT or data['address'] != '0x14046d750'
                or not data['complete'] or len(raw) != 605825 or raw[-1:] != b'\0'
                or hashlib.sha256(raw[:-1]).hexdigest() != '01fbd5a2c5d958ff12d9169de72f6f3e6540dde7af97efedfbc94231817eb917'):
            raise ValueError('Wrong or incomplete observation network evidence.')
        if args.model_output.exists():
            raise FileExistsError('Choose a new local model output.')
        args.model_output.write_bytes(raw[:-1])
